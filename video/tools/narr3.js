let total = 0;
const out = S.map((lines, i) => {
  const sceneCount = L[i].scenes.length;
  const body = lines.slice(2);
  if (body.length !== sceneCount) throw new Error(`урок ${i}: строк ${body.length}, сцен ${sceneCount}`);
  const text = lines.join(' ').replace(/\s+/g, ' ').trim();
  const sceneLines = body;
  // доля времени на каждую сцену — по длине её реплики
  const lens = sceneLines.map(s => s.length);
  const sum = lens.reduce((a, b) => a + b, 0);
  const weights = lens.map(l => l / sum);
  fs.writeFileSync(`audio/txt${i}.txt`, text);
  total += text.length;
  return {id: i, text, sceneLines, weights, head: lines[0]};
});
fs.writeFileSync('narr.json', JSON.stringify(out, null, 1));
